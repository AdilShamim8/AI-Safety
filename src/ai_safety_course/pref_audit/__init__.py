"""P04 — Preference optimization audit (stdlib-only, deterministic).

Implements Chapter 04's audit discipline as code on a synthetic,
seeded preference corpus:

- ``data``: items with true quality; noisy pairwise preference labels
  generated by a logistic observation model (the labeler is a noisy
  proxy for quality, exactly as Ch. 04 frames r_phi).
- ``bt``: the Bradley-Terry pair loss and its gradient (the course's
  own derivation, numerically checked in tests).
- ``dpo``: the DPO objective on synthetic log-ratios, with the
  closed-form optimal policy per beta (the Ch. 04 derivation).
- ``audit``: the three instruments --
  (1) proxy-vs-heldout: the learned policy's proxy score vs its
      expected TRUE quality (the proxy is optimized wherever it can
      be, including where it is wrong);
  (2) label-bias condition: flip k labels -> reward drift -> policy
      drift -> held-out objective drop;
  (3) SFT-vs-preference comparison: the uniform-on-observed policy
      vs the DPO-optimal policy on proxy and held-out.

Every quantity is deterministic given the seed; tests pin the
numbers.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from random import Random

__all__ = [
    "Item",
    "Pair",
    "PreferenceData",
    "make_preference_data",
    "bt_loss",
    "bt_gradient",
    "dpo_loss",
    "optimal_policy_from_rewards",
    "fit_reward_model",
    "AuditResult",
    "run_audit",
    "label_bias_condition",
]

INF = float("inf")


@dataclass(frozen=True)
class Item:
    """One response option with a *true* quality and a feature x."""

    item_id: int
    x: float  # observed feature the reward model can use
    true_quality: float  # the held-out objective's ground truth


@dataclass(frozen=True)
class Pair:
    """A preference pair: label says chosen > rejected (possibly wrong)."""

    chosen: int
    rejected: int
    label_correct: bool


@dataclass
class PreferenceData:
    items: list[Item]
    pairs: list[Pair]
    seed: int


def make_preference_data(
    n_items: int = 40,
    n_pairs: int = 200,
    label_noise: float = 1.0,
    seed: int = 7,
) -> PreferenceData:
    """Deterministic synthetic corpus.

    ``x`` is a noisy *view* of true quality (correlation < 1), so the
    reward model's feature is a proxy: it tracks quality but can be
    wrong per-item — the Ch. 04 seam.
    """
    rng = Random(seed)
    items: list[Item] = []
    for i in range(n_items):
        q = rng.uniform(-1.0, 1.0)
        x = q + rng.gauss(0.0, 0.6)  # noisy view
        items.append(Item(item_id=i, x=round(x, 6), true_quality=round(q, 6)))
    pairs: list[Pair] = []
    for _ in range(n_pairs):
        a, b = rng.sample(range(n_items), 2)
        # logistic labeler on TRUE quality difference + label noise
        diff = items[a].true_quality - items[b].true_quality
        p_a_wins = 1.0 / (1.0 + math.exp(-(diff / max(label_noise, 1e-9))))
        label_says_a = rng.random() < p_a_wins
        chosen, rejected = (a, b) if label_says_a else (b, a)
        correct = items[chosen].true_quality >= items[rejected].true_quality
        pairs.append(Pair(chosen=chosen, rejected=rejected, label_correct=correct))
    return PreferenceData(items=items, pairs=pairs, seed=seed)


def bt_loss(reward_diff: float) -> float:
    """Bradley-Terry pair loss: -log sigmoid(r_w - r_l)."""
    z = reward_diff
    # numerically stable log-sigmoid
    if z >= 0:
        return math.log1p(math.exp(-z))
    return -z + math.log1p(math.exp(z))


def bt_gradient(reward_diff: float) -> float:
    """dL/dz = -sigmoid(-z): the Ch. 04 gradient factor."""
    return -1.0 / (1.0 + math.exp(reward_diff))


def dpo_loss(delta_w: float, delta_l: float, beta: float = 0.1) -> float:
    """DPO loss: -log sigmoid(beta * ((delta_w) - (delta_l))).

    ``delta_w``/``delta_l`` are log(pi/pi_ref) for chosen/rejected.
    """
    return bt_loss(beta * (delta_w - delta_l))


def optimal_policy_from_rewards(rewards: dict[int, float], beta: float = 1.0) -> dict[int, float]:
    """Closed-form optimal policy: pi*(y) proportional exp(r(y)/beta).

    The Ch. 04 derivation: the KL-constrained optimum puts mass
    exp(r/beta)/Z on each option.
    """
    m = max(rewards.values())
    exps = {k: math.exp((v - m) / beta) for k, v in rewards.items()}
    z = sum(exps.values())
    return {k: e / z for k, e in exps.items()}


def fit_reward_model(data: PreferenceData, lr: float = 0.05, epochs: int = 400) -> dict[int, float]:
    """Logistic (BT) reward model on the feature x, fit by SGD.

    Deterministic (fixed-order updates, no RNG).
    """
    w, b = 0.0, 0.0
    xs = [data.items[p.chosen].x - data.items[p.rejected].x for p in data.pairs]
    for _ in range(epochs):
        gw, gb = 0.0, 0.0
        for z in xs:
            g = bt_gradient(w * z + b)  # dL/dz at z' = w*z+b
            gw += g * z
            gb += g
        w -= lr * gw / len(xs)
        b -= lr * gb / len(xs)
    return {it.item_id: w * it.x + b for it in data.items}


def _expected_true_quality(policy: dict[int, float], data: PreferenceData) -> float:
    q = {it.item_id: it.true_quality for it in data.items}
    return sum(p * q[i] for i, p in policy.items())


def _proxy_score(policy: dict[int, float], rewards: dict[int, float]) -> float:
    return sum(p * rewards[i] for i, p in policy.items())


@dataclass
class AuditResult:
    proxy_dpo: float
    proxy_sft: float
    heldout_dpo: float
    heldout_sft: float
    policy_dpo: dict[int, float] = field(repr=False, default_factory=dict)
    policy_sft: dict[int, float] = field(repr=False, default_factory=dict)


def run_audit(data: PreferenceData, beta: float = 1.0) -> AuditResult:
    """The three comparisons on the corpus (instruments 1 and 3)."""
    rewards = fit_reward_model(data)
    policy_dpo = optimal_policy_from_rewards(rewards, beta=beta)
    n = len(data.items)
    policy_sft = {i: 1.0 / n for i in range(n)}  # uniform baseline
    return AuditResult(
        proxy_dpo=_proxy_score(policy_dpo, rewards),
        proxy_sft=_proxy_score(policy_sft, rewards),
        heldout_dpo=_expected_true_quality(policy_dpo, data),
        heldout_sft=_expected_true_quality(policy_sft, data),
        policy_dpo=policy_dpo,
        policy_sft=policy_sft,
    )


@dataclass
class BiasConditionResult:
    flips: int
    heldout_clean: float
    heldout_biased: float
    drift: float


def label_bias_condition(
    data: PreferenceData, flip_fraction: float = 0.2, beta: float = 1.0
) -> BiasConditionResult:
    """Instrument 2: flip k% of labels; re-fit; measure held-out drift.

    The flipped labels are the *first* k% of pairs (deterministic),
    not random — the audit's adversarial worst case: label noise
    concentrated, not diffuse.
    """
    base = run_audit(data, beta=beta)
    n_flip = int(len(data.pairs) * flip_fraction)
    biased_pairs = []
    for idx, p in enumerate(data.pairs):
        if idx < n_flip:
            biased_pairs.append(Pair(chosen=p.rejected, rejected=p.chosen, label_correct=False))
        else:
            biased_pairs.append(p)
    biased = PreferenceData(items=data.items, pairs=biased_pairs, seed=data.seed)
    biased_res = run_audit(biased, beta=beta)
    return BiasConditionResult(
        flips=n_flip,
        heldout_clean=base.heldout_dpo,
        heldout_biased=biased_res.heldout_dpo,
        drift=biased_res.heldout_dpo - base.heldout_dpo,
    )
